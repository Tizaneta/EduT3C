
String getItemImage(String? icon) {
  switch (icon) {
    case 'monstec':
      return 'assets/images/monstec.png';

    case 'monstec2':
      return 'assets/images/monstec2.png';

    case 'monstec3':
      return 'assets/images/monstec3.png';

    default:
      return 'assets/images/default_item.png';
  }
}
